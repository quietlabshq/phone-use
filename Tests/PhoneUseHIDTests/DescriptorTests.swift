import Testing
@testable import PhoneUseHID

struct DescriptorTests {
    @Test func descriptorHasBalancedCollectionsAndExpectedReportWidths() throws {
        let bytes = ReportDescriptor.bytes
        var offset = 0
        var depth = 0
        var reportID = 0
        var size = 0
        var count = 0
        var inputBits: [Int: Int] = [:]
        var outputBits: [Int: Int] = [:]
        while offset < bytes.count {
            let prefix = bytes[offset]
            offset += 1
            let length = prefix & 3 == 3 ? 4 : Int(prefix & 3)
            try #require(offset + length <= bytes.count)
            var value = 0
            for index in 0..<length {
                value |= Int(bytes[offset + index]) << (8 * index)
            }
            offset += length
            switch prefix & 0xFC {
            case 0x84: reportID = value
            case 0x74: size = value
            case 0x94: count = value
            case 0x80: inputBits[reportID, default: 0] += size * count
            case 0x90: outputBits[reportID, default: 0] += size * count
            case 0xA0: depth += 1
            case 0xC0:
                depth -= 1
                #expect(depth >= 0)
            default: break
            }
        }
        #expect(depth == 0)
        #expect(inputBits == [1: 64, 2: 64])
        #expect(outputBits == [1: 8])
        #expect(bytes == [
            0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02,
            0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01,
            0x29, 0x20, 0x15, 0x00, 0x25, 0x01, 0x95, 0x20,
            0x75, 0x01, 0x81, 0x02, 0x05, 0x01, 0x09, 0x30,
            0x09, 0x31, 0x15, 0x00, 0x26, 0xFF, 0x7F, 0x75,
            0x10, 0x95, 0x02, 0x81, 0x02, 0xC0, 0xC0,
            0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x01,
            0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00,
            0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
            0x95, 0x01, 0x75, 0x08, 0x81, 0x03, 0x95, 0x05,
            0x75, 0x01, 0x05, 0x08, 0x19, 0x01, 0x29, 0x05,
            0x91, 0x02, 0x95, 0x01, 0x75, 0x03, 0x91, 0x03,
            0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x65,
            0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x81, 0x00, 0xC0,
        ])
    }
}
